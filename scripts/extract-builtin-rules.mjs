#!/usr/bin/env node
/**
 * Regenerate this extension's built-in rule modules from the ClearView Android
 * app's `BlockRepository.kt`.
 *
 * The Android app is the source of truth for the built-in protection rules, and
 * this extension deliberately does NOT maintain a second, hand-edited copy of
 * them: a rule added to the app must not have to be remembered here as well.
 * This script reads the Kotlin constants and writes them out as plain ES
 * modules, so the extension always ships exactly the rules the app ships.
 *
 * Usage:
 *
 *   node scripts/extract-builtin-rules.mjs path/to/BlockRepository.kt
 *
 * The default path assumes the Android repository has been cloned beside this
 * one as `../ClearView`. See the README for the exact `git clone` line.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = resolve(HERE, '..', 'src', 'common', 'rules');

const DEFAULT_SOURCE = resolve(HERE, '..', '..', 'ClearView', 'app', 'src', 'main', 'java', 'com', 'muddassir', 'clearview', 'repository', 'BlockRepository.kt');

/** The Kotlin constants this port needs, and the export name each becomes. */
const CONSTANTS = [
  ['ALWAYS_BLOCK_KEYWORDS', 'ALWAYS_BLOCK_KEYWORDS', 'keyword'],
  ['ADULT_DOMAINS', 'ADULT_DOMAINS', 'domain'],
  ['STRICT_MODE_KEYWORDS', 'STRICT_MODE_KEYWORDS', 'keyword'],
  ['COMBINATION_GENERIC_TERMS', 'COMBINATION_GENERIC_TERMS', 'keyword'],
  ['COMBINATION_RISKY_TERMS', 'COMBINATION_RISKY_TERMS', 'keyword'],
];

/**
 * Strip Kotlin comments before parsing.
 *
 * The rule blocks are heavily commented, and those comments quote terms (a
 * comment reading `("woman bikini")` would otherwise be harvested as two extra
 * rules). Comments are removed first so only real string literals survive.
 */
function stripComments(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}

/**
 * Extract every double-quoted string literal inside one `linkedSetOf( ... )`
 * initialiser.
 *
 * Scans from the declared constant's name to its opening paren and then walks
 * with a paren-depth counter, so a nested call inside the block cannot end the
 * scan early. Only depth-1 strings are collected.
 */
function extractStrings(source, constantName) {
  const declIndex = source.indexOf(`val ${constantName}`);
  if (declIndex < 0) {
    throw new Error(`constant ${constantName} not found in source`);
  }
  const openIndex = source.indexOf('linkedSetOf(', declIndex);
  if (openIndex < 0) {
    throw new Error(`linkedSetOf( not found for ${constantName}`);
  }
  const bodyStart = openIndex + 'linkedSetOf('.length;

  const values = [];
  let depth = 1;
  let i = bodyStart;
  while (i < source.length && depth > 0) {
    const ch = source[i];
    if (ch === '(') {
      depth += 1;
      i += 1;
      continue;
    }
    if (ch === ')') {
      depth -= 1;
      if (depth === 0) break;
      i += 1;
      continue;
    }
    if (ch === '"') {
      let j = i + 1;
      let value = '';
      while (j < source.length) {
        if (source[j] === '\\') {
          value += source[j + 1];
          j += 2;
          continue;
        }
        if (source[j] === '"') break;
        value += source[j];
        j += 1;
      }
      if (depth === 1) values.push(value);
      i = j + 1;
      continue;
    }
    i += 1;
  }
  return values;
}

/** De-duplicate while preserving the source order (the app uses a LinkedHashSet). */
function dedupe(values) {
  return [...new Set(values)];
}

function jsStringArrayLine(value) {
  return `  ${JSON.stringify(value)},`;
}

function listModule(exportName, values, description) {
  return `/**
 * ${description}
 *
 * GENERATED by scripts/extract-builtin-rules.mjs from the Android app's
 * BlockRepository.kt. Do not edit by hand — edit the app and re-run the script.
 */

export const ${exportName} = [
${values.map(jsStringArrayLine).join('\n')}
];
`;
}

function header(sourcePath) {
  return `Ported from ${sourcePath} by scripts/extract-builtin-rules.mjs.`;
}

function main() {
  const sourcePath = process.argv[2] ? resolve(process.argv[2]) : DEFAULT_SOURCE;
  const raw = readFileSync(sourcePath, 'utf8');
  const source = stripComments(raw);

  const parts = [];
  const counts = {};

  for (const [kotlinName, exportName, kind] of CONSTANTS) {
    const values = dedupe(extractStrings(source, kotlinName).filter((v) => v.length > 0));
    counts[kotlinName] = values.length;
    const description =
      kind === 'domain'
        ? 'Built-in adult domains. Generated from ADULT_DOMAINS.'
        : `Built-in protection terms. Generated from ${kotlinName}.`;
    parts.push(listModule(exportName, values, description));
  }

  const index = `/**
 * The built-in protection rule set, ported from the ClearView Android app.
 *
 * GENERATED by scripts/extract-builtin-rules.mjs. Do not edit by hand.
 * ${header(sourcePath)}
 *
 * These are the SAME rules the Android app enforces, in the SAME tiers:
 *
 *  - ALWAYS_BLOCK_KEYWORDS — clear adult terms, active in every mode.
 *  - ADULT_DOMAINS         — adult site hostnames, blocked at the host level.
 *  - STRICT_MODE_KEYWORDS  — risky-but-innocent discovery terms, active only
 *                            while Strict Mode is on.
 *  - COMBINATION_*         — a generic half plus a risky half blocks together
 *                            ("woman" + "bikini"), never alone.
 *
 * Community rules arrive separately (see the shared blocklist), and are merged
 * ON TOP of these, never in place of them.
 */

export * from './builtin-keywords.js';
export * from './builtin-domains.js';
export * from './combination-terms.js';
export * from './strict-mode-keywords.js';
`;

  mkdirSync(OUT_DIR, { recursive: true });
  const files = {
    'builtin-keywords.js': parts[0],
    'builtin-domains.js': parts[1],
    'strict-mode-keywords.js': parts[2],
    'combination-terms.js': `${parts[3]}\n${parts[4]}`,
    'index.js': index,
  };
  for (const [name, contents] of Object.entries(files)) {
    writeFileSync(resolve(OUT_DIR, name), contents, 'utf8');
  }

  console.log(`Wrote built-in rules from ${sourcePath}`);
  console.log(`  ALWAYS_BLOCK_KEYWORDS     ${counts.ALWAYS_BLOCK_KEYWORDS}`);
  console.log(`  ADULT_DOMAINS             ${counts.ADULT_DOMAINS}`);
  console.log(`  STRICT_MODE_KEYWORDS      ${counts.STRICT_MODE_KEYWORDS}`);
  console.log(`  COMBINATION_GENERIC_TERMS ${counts.COMBINATION_GENERIC_TERMS}`);
  console.log(`  COMBINATION_RISKY_TERMS   ${counts.COMBINATION_RISKY_TERMS}`);
}

main();
